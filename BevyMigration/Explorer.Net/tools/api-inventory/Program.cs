using System;
using System.Collections.Generic;
using System.IO;

namespace BevyMigration.Tools.ApiInventory
{
    internal static class Program
    {
        private const int EXIT_OK = 0;
        private const int EXIT_FAILED = 1;
        private const int EXIT_USAGE = 2;

        private const string USAGE =
            "usage: api-inventory <generate|check> [--solution <Explorer.sln>] [--ledger <BevyMigration/ledger>] [--force] [--report-unresolved <file>]\n"
            + "  generate  write api-inventory.json and allowlist.toml (refuses to overwrite the toml without --force)\n"
            + "  check     write api-inventory.json and fail on members outside allowlist.toml or listed in removed_by_refactor\n"
            + "Prerequisite: Explorer/Explorer.sln generated by the Unity Editor (same as scripts/lint/run-inspectcode.sh).";

        private static int Main(string[] args)
        {
            if (args.Length == 0 || (args[0] != "generate" && args[0] != "check"))
            {
                Console.Error.WriteLine(USAGE);
                return EXIT_USAGE;
            }

            string command = args[0];
            string repoRoot = RepositoryRoot.Find();
            string solution = Path.Combine(repoRoot, "Explorer", "Explorer.sln");
            string ledgerDir = Path.Combine(repoRoot, "BevyMigration", "ledger");
            bool force = false;
            string? unresolvedReport = null;

            for (var i = 1; i < args.Length; i++)
            {
                switch (args[i])
                {
                    case "--solution" when i + 1 < args.Length:
                        solution = Path.GetFullPath(args[++i]);
                        break;
                    case "--ledger" when i + 1 < args.Length:
                        ledgerDir = Path.GetFullPath(args[++i]);
                        break;
                    case "--force":
                        force = true;
                        break;
                    case "--report-unresolved" when i + 1 < args.Length:
                        unresolvedReport = Path.GetFullPath(args[++i]);
                        break;
                    default:
                        Console.Error.WriteLine(USAGE);
                        return EXIT_USAGE;
                }
            }

            if (!File.Exists(solution))
            {
                Console.Error.WriteLine($"api-inventory: {solution} does not exist; open the project in the Unity Editor (or run it in batch mode) so it generates the solution.");
                return EXIT_FAILED;
            }

            IReadOnlyList<UnityProject> projects = UnityProject.LoadSolution(solution, repoRoot, out IReadOnlyDictionary<string, string> skipped);
            Console.WriteLine($"api-inventory: {projects.Count} runtime assemblies to inventory, {skipped.Count} skipped");

            Inventory inventory = Inventory.Collect(projects, repoRoot, skipped, unresolvedReport);
            string jsonPath = Path.Combine(ledgerDir, "api-inventory.json");
            inventory.WriteJson(jsonPath);
            Console.WriteLine($"api-inventory: {inventory.Members.Count} distinct members written to {jsonPath}");

            string tomlPath = Path.Combine(ledgerDir, "allowlist.toml");

            if (command == "generate")
            {
                if (File.Exists(tomlPath) && !force)
                {
                    Console.Error.WriteLine($"api-inventory: {tomlPath} exists and is maintained by hand (plan § 6); pass --force to regenerate it.");
                    return EXIT_FAILED;
                }

                Allowlist.FromInventory(inventory).Write(tomlPath);
                Console.WriteLine($"api-inventory: allowlist written to {tomlPath}");
                return EXIT_OK;
            }

            if (!File.Exists(tomlPath))
            {
                Console.Error.WriteLine($"api-inventory: {tomlPath} does not exist; run `api-inventory generate` first.");
                return EXIT_FAILED;
            }

            Allowlist allowlist = Allowlist.Read(tomlPath);
            AllowlistCheck result = allowlist.Check(inventory);
            result.Print(Console.Out, Console.Error);
            return result.Passed ? EXIT_OK : EXIT_FAILED;
        }
    }
}
